<?php

declare(strict_types=1);


/*
|--------------------------------------------------------------------------
| START SESSION
|--------------------------------------------------------------------------
| Start only if a session is not already active.
|--------------------------------------------------------------------------
*/

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| CHECK LOGIN
|--------------------------------------------------------------------------
*/

if (empty($_SESSION['user_id'])) {

    header('Location: /YAKAP/auth/login.php');

    exit;
}